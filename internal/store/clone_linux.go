//go:build linux

package store

import (
	"os"

	"golang.org/x/sys/unix"
)

// cloneFile creates dst as a reflink of src with the FICLONE ioctl. It
// fails on file systems without reflinks and across file systems.
func cloneFile(src, dst string) error {
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()
	out, err := os.OpenFile(dst, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		return err
	}
	if err := unix.IoctlFileClone(int(out.Fd()), int(in.Fd())); err != nil {
		out.Close()
		os.Remove(dst)
		return err
	}
	return out.Close()
}
